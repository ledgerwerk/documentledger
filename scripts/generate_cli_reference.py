#!/usr/bin/env python3
"""Generate the stable Markdown CLI reference from command metadata and Click."""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Any, get_args, get_origin

from click import Argument, Command
from typer.main import get_command

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))
OUTPUT = ROOT / "docs" / "cli.md"


def _command_for(root: Command, path: str) -> Command:
    command: Any = root
    for name in path.split():
        command = command.commands[name]
    return command


def _default(value: Any) -> str:
    if value is None or value is False:
        return ""
    return repr(value)


_CANONICAL_TYPE_NAMES = {"text": "str", "integer": "int", "bool": "boolean"}


def _canonical_type_name(name: str) -> str:
    return _CANONICAL_TYPE_NAMES.get(name, name)


def _parameter_type_name(parameter: Any) -> str:
    parameter_type = getattr(parameter, "type", None)
    if parameter_type is not None:
        name = getattr(parameter_type, "name", str(parameter_type))
    else:
        annotation = getattr(getattr(parameter, "type_descriptor", None), "annotation", None)
        if get_origin(annotation) is list:
            arguments = get_args(annotation)
            item_name = getattr(arguments[0], "__name__", str(arguments[0])) if arguments else "Any"
            name = f"list[{item_name}]"
        else:
            name = getattr(annotation, "__name__", str(annotation))
    return _canonical_type_name(name)


def _parameters(command: Command) -> str:
    if not command.params:
        return "- None."
    rows = ["| Parameter | Required | Default | Type |", "| --- | --- | --- | --- |"]
    for parameter in command.params:
        if isinstance(parameter, Argument):
            name = parameter.name
        else:
            name = ", ".join(parameter.opts)
        kind = _parameter_type_name(parameter)
        rows.append(f"| `{name}` | {'yes' if parameter.required else 'no'} | `{_default(parameter.default)}` | `{kind}` |")
    return "\n".join(rows)


def _align_markdown_tables(text: str) -> str:
    lines = text.splitlines()
    result: list[str] = []
    index = 0
    while index < len(lines):
        line = lines[index]
        if not line.startswith("|") or not line.endswith("|"):
            result.append(line)
            index += 1
            continue

        table: list[list[str]] = []
        while index < len(lines) and lines[index].startswith("|") and lines[index].endswith("|"):
            table.append([cell.strip() for cell in lines[index].strip("|").split("|")])
            index += 1

        widths = [max(3, max(len(row[column]) for row in table)) for column in range(len(table[0]))]
        for row in table:
            if all(cell and set(cell) <= {"-", ":"} and "-" in cell for cell in row):
                cells = ["-" * width for width in widths]
            else:
                cells = [cell.ljust(widths[column]) for column, cell in enumerate(row)]
            result.append("| " + " | ".join(cells) + " |")

    return "\n".join(result) + ("\n" if text.endswith("\n") else "")


def render() -> str:
    from documentledger.cli import app
    from documentledger.command_catalog import COMMAND_INVENTORY, COMMAND_REFERENCE_DETAILS

    root = get_command(app)
    canonical_reference_intro = (
        "This is the authoritative canonical command reference. "
        "It is generated from `COMMAND_INVENTORY` and the registered Click command tree; "
        "run the generator check in CI after command changes."
    )
    json_contract_description = (
        "With `--json`, the command returns `ok`, `command`, a command-specific `result`, "
        "and `events`. Failures return the normalized `error` object with `code`, `message`, "
        "`remediation`, and `details.domain_code`. Invalid workspace, selector, cursor, link, "
        "or migration state is reported before a write when applicable."
    )
    lines = [
        "# CLI reference",
        "",
        "<!-- This file is generated by scripts/generate_cli_reference.py. -->",
        "",
        canonical_reference_intro,
        "",
        "## Global options",
        "",
        "Global options may appear before the command path:",
        "",
        "| Option | Effect |",
        "| --- | --- |",
        "| `--root PATH` | Resolve the project from PATH instead of the current directory. |",
        "| `--json` | Emit the stable JSON envelope. |",
        "| `--profile` | Include diagnostic operation events in JSON output. |",
        "| `--version` | Show the installed version. |",
        "| `--install-completion` | Install shell completion. |",
        "| `--show-completion` | Print shell completion. |",
        "",
        "## Canonical commands",
        "",
    ]
    for entry in COMMAND_INVENTORY.entries:
        command = _command_for(root, entry.path)
        aliases = ", ".join(f"`{alias}`" for alias in entry.aliases) or "None"
        workspace = "yes" if entry.requires_workspace else "no"
        details = COMMAND_REFERENCE_DETAILS.get(entry.path, {})
        extended_description = details.get("extended_description")
        json_result = details.get("json_result", json_contract_description)
        examples = details.get("examples", (f"documentledger {entry.path}",))
        summary_lines = [entry.summary]
        if extended_description:
            summary_lines.extend(["", extended_description])
        example_lines = [line for example in examples for line in ("```bash", *example.splitlines(), "```", "")]
        lines.extend(
            [
                f"## {entry.path}",
                "",
                *summary_lines,
                "",
                f"- **Effect:** `{entry.effect}`",
                f"- **Audience:** `{entry.audience}`",
                f"- **Workspace required:** `{workspace}`",
                f"- **Targeting:** `{entry.targeting}`",
                f"- **Compatibility aliases:** {aliases}",
                "",
                "### Syntax",
                "",
                f"```bash\ndocumentledger {entry.path}\n```",
                "",
                "### Arguments and options",
                "",
                _parameters(command),
                "",
                "### JSON result and errors",
                "",
                json_result,
                "",
                "### Examples",
                "",
                *example_lines,
            ]
        )
    lines.extend(
        [
            "## Compatibility commands",
            "",
            "Compatibility interfaces are documented separately and are not canonical inventory entries:",
            "",
            "| Compatibility path | Use instead |",
            "| --- | --- |",
            "| `docledger` executable | `documentledger` |",
            "| `docs ...` | `document ...` |",
            "| `sources ...` | `source ...` |",
            "| `links ...` | `link ...` |",
            "| root `mark-fresh` | `document mark-fresh` |",
            "| `storage verify` | `storage validate` |",
            "| `storage migrate` | `migrate plan` or `migrate apply` |",
            "| `storage recover` | `migrate recover` |",
            "| `storage cleanup-legacy` | `migrate cleanup` |",
            "",
            ":::{deprecated} 0.6",
            "These wrappers remain for compatibility and may emit deprecation warnings. New automation must use canonical command paths.",
            ":::",
            "",
        ]
    )
    return _align_markdown_tables("\n".join(lines))


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the checked-in reference differs")
    args = parser.parse_args()
    rendered = render()
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != rendered:
            print(f"{OUTPUT} is out of date; run python scripts/generate_cli_reference.py", file=sys.stderr)
            return 1
        print(f"{OUTPUT} is up to date")
        return 0
    OUTPUT.write_text(rendered, encoding="utf-8")
    print(f"wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
